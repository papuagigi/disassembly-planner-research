"""Aggregate v7.2 collection / validation / retry metrics into analysis/ tables (no model call, no physics).

usage: python -m disassembly_repair_v7_2.offline.aggregate
Writes analysis/{collection,validation,retry}_runs.csv, analysis/summary_v72.json and analysis/RESULT_TABLES.md.
Every finished episode is included; nothing is filtered by outcome.
"""
from __future__ import annotations
import csv
import statistics

from ..common import ROOT, read, write, utc

FIELDS = ['stage', 'case_id', 'label', 'arm', 'memory', 'rep', 'success', 'termination_class', 'best_removed', 'required_removed',
          'checks', 'failed_checks', 'cached_rejections', 'restores', 'llm_calls', 'input_tokens', 'output_tokens', 'total_tokens',
          'elapsed_seconds', 'first_valid_action_check', 'document_reads', 'deadline_stops', 'native_engine_errors']


def _memory(bank_path):
    # bank file stem -> memory condition: S0 (no documents), S3copy/S3, S4b, <base>_note_<cad> -> <base>+note
    stem = bank_path.rsplit('/', 1)[-1].removesuffix('.json')
    if stem == 'S0':
        return 'none'
    if '_note_' in stem:
        return stem.split('_note_')[0].replace('S3copy', 'S3') + '+note'
    return stem.replace('S3copy', 'S3')


def rows(stage):
    out = []
    for p in sorted((ROOT / 'outputs' / stage).glob('*/*/metrics.json')):
        m = read(p)
        job = read(p.parent / 'job.json')
        label = p.parent.name
        arm, memory = job['arm'], _memory(job['bank_path'])
        rep = int(label.rsplit('_r', 1)[1]) if '_r' in label and label.rsplit('_r', 1)[1].isdigit() else 1
        row = dict(stage=stage, case_id=p.parent.parent.name, label=label, arm=arm, memory=memory, rep=rep)
        row.update({k: m.get(k) for k in FIELDS if k not in row})
        row['elapsed_seconds'] = round(row['elapsed_seconds'] or 0., 1)
        out.append(row)
    return out


def group(rs):
    succ = [r for r in rs if r['success']]
    mean = lambda k, xs: round(statistics.mean([x[k] or 0 for x in xs]), 1) if xs else None  # noqa: E731
    return dict(runs=len(rs), successes=len(succ),
                median_checks_successful=statistics.median([r['checks'] for r in succ]) if succ else None,
                mean_checks=mean('checks', rs), mean_best_removed=mean('best_removed', rs),
                mean_elapsed_seconds=mean('elapsed_seconds', rs), mean_llm_calls=mean('llm_calls', rs),
                mean_total_tokens=mean('total_tokens', rs), mean_cached_rejections=mean('cached_rejections', rs))


def _csv(path, rs):
    with open(path, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        for r in rs:
            w.writerow({k: r.get(k) for k in FIELDS})


def _md_runs(rs):
    head = ('| CAD | run | arm/memory | success | removed/required | checks | cached rej. | calls | tokens | s | end |\n'
            '|---|---|---|---|---|---|---|---|---|---|---|\n')
    return head + ''.join(f"| {r['case_id'][5:]} | {r['label']} | {r['arm']}/{r['memory']} | {'Y' if r['success'] else 'N'} | "
                          f"{r['best_removed']}/{r['required_removed']} | "
                          f"{r['checks']} | {r['cached_rejections']} | {r['llm_calls']} | {r['total_tokens']} | {r['elapsed_seconds']} | "
                          f"{r['termination_class']} |\n" for r in rs)


def _md_groups(groups):
    head = ('| group | runs | success | median checks (successful) | mean checks | mean removed | mean s | mean calls | mean tokens |\n'
            '|---|---|---|---|---|---|---|---|---|\n')
    return head + ''.join(f"| {k} | {g['runs']} | {g['successes']}/{g['runs']} | {g['median_checks_successful']} | {g['mean_checks']} | "
                          f"{g['mean_best_removed']} | {g['mean_elapsed_seconds']} | {g['mean_llm_calls']} | {g['mean_total_tokens']} |\n"
                          for k, g in groups.items())


def main():
    analysis = ROOT / 'analysis'
    analysis.mkdir(exist_ok=True)
    summary, md = dict(utc=utc()), ['# v7.2 result tables (generated by offline/aggregate.py; all finished episodes, unfiltered)\n']
    for stage in ('collection', 'validation', 'retry'):
        rs = rows(stage)
        if not rs:
            continue
        _csv(analysis / f'{stage}_runs.csv', rs)
        attempt = lambda r: 'first' if r['label'].startswith('first') else 'second'  # noqa: E731
        if stage == 'retry':
            keys = sorted({(attempt(r), r['arm'], r['memory']) for r in rs})
            groups = {f'{a}/{arm}/{mem}': group([r for r in rs if (attempt(r), r['arm'], r['memory']) == (a, arm, mem)])
                      for a, arm, mem in keys}
            per_cad = {cid: {f'{a}/{arm}/{mem}': group([r for r in rs if r['case_id'] == cid
                                                        and (attempt(r), r['arm'], r['memory']) == (a, arm, mem)])
                             for a, arm, mem in keys} for cid in sorted({r['case_id'] for r in rs})}
            summary[stage] = dict(groups=groups, per_cad=per_cad, runs=rs)
        else:
            keys = sorted({(r['arm'], r['memory']) for r in rs})
            groups = {f'{arm}/{mem}': group([r for r in rs if (r['arm'], r['memory']) == (arm, mem)]) for arm, mem in keys}
            summary[stage] = dict(groups=groups, runs=rs)
        md.append(f'\n## {stage}\n\n' + _md_groups(groups) + '\n' + _md_runs(rs))
        if stage == 'retry':
            for cid, g in summary[stage]['per_cad'].items():
                md.append(f'\n### retry {cid}\n\n' + _md_groups(g))
    for name in ('validation', 'retry'):
        for p in (ROOT / 'outputs/replay').glob(f'{name}*.json'):
            a = read(p)
            summary.setdefault('replay', {})[p.stem] = dict(status=a['status'], episodes=len(a['episodes']))
    if (ROOT / 'outputs/validation/decision.json').exists():
        d = read(ROOT / 'outputs/validation/decision.json')
        summary['admission'] = dict(admitted=d['admitted'], passes=d['passes'])
        md.append(f"\nS4b admission (pre-registered rule): admitted={d['admitted']}, passes={d['passes']}\n")
    if summary.get('replay'):
        md.append('\nIndependent replays: ' + ', '.join(f"{k} {v['status']} ({v['episodes']})" for k, v in summary['replay'].items()) + '\n')
    write(analysis / 'summary_v72.json', summary)
    (analysis / 'RESULT_TABLES.md').write_text(''.join(md), encoding='utf-8')
    print(''.join(md))


if __name__ == '__main__':
    main()
